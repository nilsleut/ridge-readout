"""
check_sessions.py
=================
Read-only check: in which session(s) and runs do the 720 evaluation stimuli lie, per
subject? Reads the THINGS-fMRI stimulus metadata (THINGS_FMRI_DIR,
sub-XX_task-things_stimulus-metadata.csv) and the stimulus order
(OUTPUTS_720_DIR/stim_order_sub-01.txt, via common_up_pairs.stim_order). Computes
nothing else and fits nothing.

Output: reports/SESSIONS_CHECK.md
"""
import subprocess
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
sys.path.insert(0, str(REPO / "src" / "ridge"))
sys.path.insert(0, str(REPO / "src" / "vendor"))

import paths                                   # noqa: E402
from common_up_pairs import SUBJECTS, stim_order  # noqa: E402
from config_hash import config_hash            # noqa: E402

OUT = REPO / "reports" / "SESSIONS_CHECK.md"


def main():
    order = stim_order()
    if len(order) != 720 or len(set(order)) != 720:
        raise SystemExit(f"STOP: expected 720 distinct stimuli, got {len(order)} ({len(set(order))} distinct)")
    rows, runs = [], {}
    for s in SUBJECTS:
        meta = pd.read_csv(paths.things_fmri_dir() / f"{s}_task-things_stimulus-metadata.csv")
        hit = meta[meta.stimulus.isin(order)]
        if len(hit) != 720 or hit.stimulus.nunique() != 720:
            raise SystemExit(f"STOP: {s}: {len(hit)} metadata rows for the 720 stimuli "
                             f"({hit.stimulus.nunique()} distinct)")
        m = hit.set_index("stimulus").loc[order]
        runs[s] = m.run.tolist()
        sessions = sorted(int(x) for x in m.session.unique())
        rows.append(dict(subject=s, sessions=", ".join(map(str, sessions)), n_sessions=len(sessions),
                         n_stimuli=len(m), n_runs=int(m.run.nunique()),
                         trial_types=", ".join(sorted(m.trial_type.unique())),
                         stimuli_per_run=" / ".join(str(int(v)) for v in m.run.value_counts().sort_index())))
    one = all(r["n_sessions"] == 1 for r in rows)
    head = subprocess.run(["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"],
                          capture_output=True, text=True, check=True).stdout.strip()
    lines = [
        "# Session check of the 720 evaluation stimuli",
        "",
        f"Generated by `scripts/check_sessions.py` (read-only; config hash `{config_hash()}`, git HEAD "
        f"`{head}`). Source: `THINGS_FMRI_DIR/sub-XX_task-things_stimulus-metadata.csv`, matched on the "
        "720 entries of `stim_order_sub-01.txt`.",
        "",
        "| Subject | Session ID(s) | Stimuli | Runs | Trial type | Stimuli per run |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| {r['subject']} | {r['sessions']} | {r['n_stimuli']} | {r['n_runs']} | "
                     f"{r['trial_types']} | {r['stimuli_per_run']} |")
    lines += [
        "",
        f"- All 720 stimuli lie in exactly one session in every subject: **{'yes' if one else 'no'}**.",
        f"- Run assignment of the 720 identical to sub-01: sub-02 "
        f"**{'yes' if runs['sub-02'] == runs['sub-01'] else 'no'}**, sub-03 "
        f"**{'yes' if runs['sub-03'] == runs['sub-01'] else 'no'}**.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
