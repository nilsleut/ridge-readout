# ── Fig 4: gain axis ──────────────────────────────────────────────────────────
def fig4():
    n = "gain"
    own = read("step7/gain.csv", "kind == 'c_gain' and in_G1 == True", n)
    imn = read("step8/generalization.csv", "kind == 'c_gain'", n)
    vox = read("step7/gain.csv", "kind == 'stimulus_corr' and what.str.startswith('voxel gain V1') and res == 224", n)
    mod = read("step7/gain.csv", "kind == 'stimulus_corr' and what.str.startswith('model gain Conv1') and res == 224", n)
    gg = read("step8/generalization_gain.csv", "model != 'brain V1'", n)
    fig, ax = plt.subplots(1, 3, figsize=(TWO, 3.6), gridspec_kw={"width_ratios": [1, 1, 1.3]})
    conds = sorted(own.cond.unique(), key=lambda c: (c.startswith("UPSAMPLED"), int(c.split("_")[1])))
    marks = dict(zip(conds, ["o", "s", "^", "v", "D", "P", "X"]))
    for r in own.itertuples():
        ax[0].scatter(r.c_gain, r.rsa_raw_V1, color=RULE_COL[r.rule], marker=marks[r.cond], s=12, lw=0)
    ax[0].set_xlabel("$c_{gain}$")
    ax[0].set_ylabel("RSA, raw features (V1)")
    ax[0].set_title("(a) CIFAR CNN", loc="left")
    h = [plt.Line2D([], [], color=RULE_COL[k], marker="o", ls="none", ms=4, label=k.replace("Random Weights", "Random"))
         for k in (R_, BP)]
    h += [plt.Line2D([], [], color="0.4", marker=marks[c], ls="none", ms=4, label=c.replace("_", " ").title()) for c in conds]
    ax[0].legend(handles=h, frameon=False, fontsize=6, loc="upper center", bbox_to_anchor=(0.5, -0.2), ncol=2)
    for r in imn.itertuples():
        col = OI["blue"] if r.cond == "trained" else OI["vermillion"]
        ax[1].scatter(r.c_gain, r.rsa_raw_V1, color=col, marker=IMN_MARK[r.model], s=12, lw=0)
    ax[1].set_xlabel("$c_{gain}$")
    ax[1].set_title("(b) ImageNet models", loc="left")
    h = [plt.Line2D([], [], color=OI["blue"], marker="o", ls="none", ms=4, label="trained"),
         plt.Line2D([], [], color=OI["vermillion"], marker="o", ls="none", ms=4, label="untrained")]
    h += [plt.Line2D([], [], color="0.4", marker=IMN_MARK[m], ls="none", ms=4, label=m) for m in IMN]
    ax[1].legend(handles=h, frameon=False, fontsize=6, loc="upper center", bbox_to_anchor=(0.5, -0.22), ncol=2)
    rows = []
    for r in vox.itertuples():
        rows.append((f"V1 voxels {r.what.split()[-1]}", r.stat, r.pearson))
    for r in mod.itertuples():
        rows.append((r.what.replace("model gain Conv1 ", "CNN ").replace("Random Weights", "Random"), r.stat, r.pearson))
    gm = gg.assign(group=np.where(gg.cond == "trained", "trained", "untrained")).groupby(["model", "group"])[
        ["corr_luminance", "corr_rms_contrast"]].mean().reset_index()
    for r in gm.itertuples():
        rows.append((f"{r.model} {r.group}", "mean luminance", r.corr_luminance))
        rows.append((f"{r.model} {r.group}", "RMS contrast", r.corr_rms_contrast))
    bars = pd.DataFrame(rows, columns=["label", "stat", "r"])
    labels = list(dict.fromkeys(bars.label))
    y = np.arange(len(labels))
    for k, (stat, col) in enumerate((("mean luminance", OI["orange"]), ("RMS contrast", OI["skyblue"]))):
        v = bars[bars.stat == stat].set_index("label").reindex(labels).r
        ax[2].barh(y + (k - 0.5) * 0.4, v, height=0.4, color=col, label=stat)
    ax[2].set_yticks(y, labels, fontsize=6)
    ax[2].invert_yaxis()
    ax[2].axvline(0, color=OI["black"], lw=0.6)
    ax[2].set_xlabel("Pearson r with gain axis")
    ax[2].set_title("(c) Gain vs stimulus", loc="left")
    ax[2].legend(frameon=False, fontsize=6, loc="upper center", bbox_to_anchor=(0.35, -0.16), ncol=1)
    fig.subplots_adjust(left=0.08, right=0.98, top=0.92, bottom=0.36, wspace=0.75)
    save(fig, n)


# ── Fig 5: gain / geometry separation ─────────────────────────────────────────
def fig5():
    n = "separation"
    con = read("step9/separation.csv", "kind == 'contrast' and F == 'center'", n)
    slo = read("step9/separation_slopes.csv", "kind == 'slope' and F == 'center' and component == 'angle' and model != 'own CNN'", n)
    models = ["own CNN"] + IMN
    cols = [("V1", "norm", "V1, norm (gain)"), ("V1", "angle", "V1, angle (geometry)"), ("LOC", "angle", "LOC, angle (geometry)")]
    fig, ax = plt.subplots(1, 4, figsize=(TWO, 2.6), sharey=True, gridspec_kw={"width_ratios": [1, 1, 1, 1]})
    y = np.arange(len(models))
    for a, (roi, comp, title) in zip(ax[:3], cols):
        q = con[(con.roi == roi) & (con.component == comp)].set_index("model").reindex(models)
        for i, m in enumerate(models):
            r = q.loc[m]
            col = OI["vermillion"] if m == "own CNN" else OI["blue"]
            a.plot([r.ci_lo, r.ci_hi], [i, i], color=col, lw=1.2)
            a.plot(r.value, i, marker="o", color=col, ms=3.5)
        a.axvline(0, color=OI["black"], lw=0.6)
        a.set_title(title)
    ax[0].set_yticks(y, models)
    ax[0].invert_yaxis()
    q = slo.set_index("model")
    for i, m in enumerate(models):
        if m in q.index:
            r = q.loc[m]
            ax[3].plot([r.ci_lo, r.ci_hi], [i, i], color=OI["green"], lw=1.2)
            ax[3].plot(r.value, i, marker="s", color=OI["green"], ms=3.5)
    ax[3].axvline(0, color=OI["black"], lw=0.6)
    ax[3].set_title("V1 angle, 224 to 448 px")
    fig.supxlabel("Contrast (V1: untrained $-$ trained; LOC: trained $-$ untrained), 95% CI", fontsize=9)
    fig.tight_layout()
    save(fig, n)


def main():
    for f in (fig1, fig2, fig3, fig4, fig5):
        f()
    print(f"wrote {len(SOURCES)} figures to {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
