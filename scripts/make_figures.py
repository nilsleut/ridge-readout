"""
make_figures.py
===============
Figures 1-5 for paper/main.tex, read only from results/ (no data values in this file).
Deterministic vector PDFs in paper/figures/, each with <name>_sources.txt listing the
source files and row filters.

Style: Okabe-Ito colours, serif font, 8 pt tick labels, 9 pt axis labels; widths
3.5 in (single column) and 7.0 in (double column). No numbers in titles.

Run:  python scripts/make_figures.py
"""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt                       # noqa: E402
import numpy as np                                    # noqa: E402
import pandas as pd                                   # noqa: E402
from matplotlib.colors import LinearSegmentedColormap, TwoSlopeNorm  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
RES = REPO / "results"
OUT = REPO / "paper" / "figures"

OI = {"black": "#000000", "orange": "#E69F00", "skyblue": "#56B4E9", "green": "#009E73",
      "yellow": "#F0E442", "blue": "#0072B2", "vermillion": "#D55E00", "purple": "#CC79A7"}
DIVERGE = LinearSegmentedColormap.from_list("oi_div", [OI["blue"], "#FFFFFF", OI["vermillion"]])
ONE, TWO = 3.5, 7.0
R_, BP, BN = "Random Weights", "Backprop", "Random Weights (BN-calibrated)"
RULE_COL = {R_: OI["vermillion"], BP: OI["blue"], "Feedback Alignment": OI["green"],
            "Predictive Coding": OI["purple"], "STDP": OI["orange"], BN: OI["skyblue"]}
IMN = ["alexnet", "vgg11_bn", "resnet18", "resnet50", "convnext_tiny", "vit_b_16"]
IMN_MARK = dict(zip(IMN, ["o", "s", "^", "v", "D", "P"]))

plt.rcParams.update({
    "font.family": "serif", "font.size": 8, "axes.labelsize": 9, "axes.titlesize": 9,
    "xtick.labelsize": 8, "ytick.labelsize": 8, "legend.fontsize": 7,
    "pdf.fonttype": 42, "axes.spines.top": False, "axes.spines.right": False,
    "svg.hashsalt": "ridge-readout",
})

SOURCES = {}


def read(rel, query, label):
    """Read a CSV from results/ and filter it; record the (file, filter) pair."""
    df = pd.read_csv(RES / rel, low_memory=False).query(query, engine="python")
    if df.empty:
        raise SystemExit(f"{label}: no rows for {rel} | {query}")
    SOURCES.setdefault(label, []).append(f"results/{rel} | {query}")
    return df


def save(fig, name):
    OUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / f"{name}.pdf", metadata={"CreationDate": None, "ModDate": None,
                                               "Creator": None, "Producer": None})
    plt.close(fig)
    (OUT / f"{name}_sources.txt").write_text(
        f"{name}.pdf -- generated by scripts/make_figures.py\n" + "\n".join(SOURCES[name]) + "\n", encoding="utf-8")


# ── Fig 1 ─────────────────────────────────────────────────────────────────────
def fig1():
    n = "sign_flip"
    pts = read("step5/resolution_rsa.csv", "kind == 'gap_point' and roi == 'V1' and layer == 'Conv1'", n)
    cis = read("step5/paper_comparisons_raw_vs_z.csv",
               "kind == 'comparison' and quantity.str.startswith('gap V1 ')", n)
    rid = read("step6/ridge_resolution.csv",
               "kind == 'difference' and subject == 'mean sub-01/02' and quantity == 'Random Weights - Backprop'", n)
    nat = sorted(pts[pts.arm == "NATIVE"].res.unique())
    xpos = {("NATIVE", r): i for i, r in enumerate(nat)}
    xpos[("UPSAMPLED", 224)] = len(nat) + 0.8
    fig, ax = plt.subplots(figsize=(TWO, 2.6))
    ax.axhline(0, color=OI["black"], lw=0.6)
    ax.axvline(len(nat) - 0.1, color="0.75", lw=0.6, ls=":")
    series = [("raw", "RSA, raw features", OI["vermillion"], "o"), ("z", "RSA, channel z-scored", OI["blue"], "s")]
    for k, (var, lab, col, mk) in enumerate(series):
        q = pts[pts.variant == var]
        nq = q[q.arm == "NATIVE"].sort_values("res")
        ax.plot([xpos[("NATIVE", r)] for r in nq.res], nq.value, color=col, marker=mk, ms=3.5, lw=1.2, label=lab)
        up = q[q.arm == "UPSAMPLED"]
        ax.plot([xpos[("UPSAMPLED", 224)]] * len(up), up.value, color=col, marker=mk, ms=3.5, ls="none", mfc="white")
        for c in cis[cis.variant == var].itertuples():
            arm = "UPSAMPLED" if "UPSAMPLED" in c.quantity else "NATIVE"
            px = int(c.quantity.split(":")[0].split()[-1])
            x = xpos[(arm, px)] + (k - 1) * 0.08
            ax.plot([x, x], [c.ci_lo, c.ci_hi], color=col, lw=1.0)
    rn = rid[rid.arm == "NATIVE"].sort_values("res")
    ax.errorbar([xpos[("NATIVE", int(r))] + 0.08 for r in rn.res], rn["mean"], yerr=rn["sd"], color=OI["green"],
                marker="^", ms=3.5, lw=1.2, capsize=2, label="Ridge, median r (sub-01/02)")
    ru = rid[rid.arm == "UPSAMPLED"]
    ax.errorbar([xpos[("UPSAMPLED", 224)] + 0.08] * len(ru), ru["mean"], yerr=ru["sd"], color=OI["green"],
                marker="^", ms=3.5, ls="none", mfc="white", capsize=2)
    ax.set_xticks([xpos[("NATIVE", r)] for r in nat] + [xpos[("UPSAMPLED", 224)]])
    ax.set_xticklabels([str(int(r)) for r in nat] + ["224\n(upsampled)"])
    ax.set_xlabel("Evaluation resolution (px)")
    ax.set_ylabel("Random $-$ Backprop, V1")
    ax.legend(frameon=False, loc="upper left")
    fig.tight_layout()
    save(fig, n)


# ── Fig 2 / 3: multiverse grids ───────────────────────────────────────────────
FS, DS, BS = ["raw", "center", "scale", "z"], ["correlation", "cosine", "euclidean"], ["paper", "center720", "z720"]


def grid(ax, cells, title, vmax):
    M = np.full((len(FS), len(DS) * len(BS)), np.nan)
    sig = np.zeros_like(M, dtype=bool)
    for r in cells.itertuples():
        i, j = FS.index(r.F), BS.index(r.B) * len(DS) + DS.index(r.D)
        M[i, j] = r.value
        sig[i, j] = bool(r.ci_lo > 0 or r.ci_hi < 0)
    im = ax.imshow(M, cmap=DIVERGE, norm=TwoSlopeNorm(0, -vmax, vmax), aspect="auto")
    for i in range(M.shape[0]):
        for j in range(M.shape[1]):
            if sig[i, j]:
                ax.plot(j, i, marker="o", ms=3, color=OI["black"])
    pi, pj = FS.index("raw"), BS.index("paper") * len(DS) + DS.index("correlation")
    ax.add_patch(plt.Rectangle((pj - 0.5, pi - 0.5), 1, 1, fill=False, ec=OI["black"], lw=1.6))
    ax.set_yticks(range(len(FS)), FS)
    ax.set_xticks(range(M.shape[1]), [d[:4] for _ in BS for d in DS], rotation=90)
    for b, B in enumerate(BS):
        ax.text(b * len(DS) + 1, -0.62, B, ha="center", va="bottom", fontsize=7)
    for b in range(1, len(BS)):
        ax.axvline(b * len(DS) - 0.5, color="white", lw=2)
    ax.set_ylabel("Feature normalisation F")
    ax.set_title(title, pad=22)
    ax.spines[:].set_visible(False)
    return im


def fig2():
    n = "multiverse_v1"
    g = read("step7/multiverse.csv", "kind == 'cell' and roi == 'V1' and quantity == 'gap NATIVE 224: Random Weights - Backprop'", n)
    s = read("step7/multiverse.csv", "kind == 'cell' and quantity == 'S = gap NAT224 - gap NAT32'", n)
    fig, axes = plt.subplots(1, 2, figsize=(TWO, 2.9))
    for ax, d, t in ((axes[0], g, "V1 gap at 224 px"), (axes[1], s, "Resolution slope S")):
        vmax = float(np.nanmax(np.abs(d.value)))
        im = grid(ax, d, t, vmax)
        cb = fig.colorbar(im, ax=ax, shrink=0.8)
        cb.ax.tick_params(labelsize=7)
    axes[1].set_ylabel("")
    fig.supxlabel("Distance D within fMRI normalisation B", fontsize=9)
    fig.tight_layout()
    save(fig, n)


