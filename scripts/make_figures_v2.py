"""
make_figures_v2.py
==================
The four new figures of manuscript v2, read only from aggregated CSVs in results/ (no voxel- or
RDM-level data, no data values in this file). The plotted data are written to results/figures_v2/
(one CSV per figure); the PDFs go to paper/figures/ with <name>_sources.txt.

  conv   (FIG-CONV)  paper cell under the three voxel normalisation conventions per data set,
                     per subject, mean +/- SD over subjects; and the standardised cell
  nsd    (FIG-NSD)   NSD per subject, V1 and LO-obj: raw/correlation, z/correlation,
                     raw/Euclidean, N, A (k = 3) and ridge g = 4, NSD standard normalisation
  multi  (FIG-MULTI) the 28 distinct analyses in THINGS, NSD (N-session) and NSD (N-raw)
  amp    (FIG-AMP)   Spearman of g and g^M with L, C, CE; model amplitude dominance; Delta before
                     and after the two-sided partial

results/step48/amplitude.csv is read through tables_v2.amplitude48(), which reconstructs the
seeds of the THINGS rows exactly as step 48b did.

Style as scripts/make_figures.py (Okabe-Ito colours, serif font, 3.5 / 7.0 in widths).
Run:  python scripts/make_figures_v2.py
"""
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt                       # noqa: E402
import numpy as np                                    # noqa: E402
import pandas as pd                                   # noqa: E402

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "scripts"))
import tables_v2                                      # noqa: E402

RES = REPO / "results"
OUT = REPO / "paper" / "figures"
DATA = RES / "figures_v2"
OI = {"black": "#000000", "orange": "#E69F00", "skyblue": "#56B4E9", "green": "#009E73",
      "yellow": "#F0E442", "blue": "#0072B2", "vermillion": "#D55E00", "purple": "#CC79A7", "grey": "#888888"}
ONE, TWO = 3.5, 7.0
plt.rcParams.update({
    "font.family": "serif", "font.size": 8, "axes.labelsize": 9, "axes.titlesize": 9,
    "xtick.labelsize": 7, "ytick.labelsize": 8, "legend.fontsize": 7,
    "pdf.fonttype": 42, "axes.spines.top": False, "axes.spines.right": False,
})
SOURCES = {}


def read(rel, query, label):
    if rel == "step48/amplitude.csv":
        df = tables_v2.amplitude48().query(query, engine="python")
    else:
        df = pd.read_csv(RES / rel, low_memory=False).query(query, engine="python")
    if df.empty:
        raise SystemExit(f"{label}: no rows for {rel} | {query}")
    SOURCES.setdefault(label, []).append(f"results/{rel} | {query}")
    return df


def save(fig, name, data):
    OUT.mkdir(parents=True, exist_ok=True)
    DATA.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / f"{name}.pdf", metadata={"CreationDate": None, "ModDate": None, "Creator": None, "Producer": None})
    plt.close(fig)
    data.to_csv(DATA / f"{name}.csv", index=False, lineterminator="\n")
    (OUT / f"{name}_sources.txt").write_text(
        f"{name}.pdf -- generated by scripts/make_figures_v2.py; plotted data in results/figures_v2/{name}.csv\n"
        + "\n".join(SOURCES[name]) + "\n", encoding="utf-8", newline="\n")


CONVS = {"THINGS-720": ["T-raw", "T-global", "T-session"], "THINGS test (k = 1)": ["T-raw", "T-global", "T-session"],
         "NSD (k = 1)": ["N-raw", "N-global", "N-session"]}
CCOL = {"raw": OI["vermillion"], "global": OI["orange"], "session": OI["blue"]}


def fig_conv():
    n = "conv"
    rows = []
    for units in ("raw", "z"):
        q = f"roi == 'V1' and units == '{units}' and distance == 'correlation'"
        a = read("step48/conventions.csv", f"kind == 'things720_subject' and {q}", n)
        rows += [dict(dataset="THINGS-720", units=units, convention=r.convention, subject=r.subject, delta=r.delta) for r in a.itertuples()]
        b = read("step48/conventions.csv", f"kind == 'things_test_subject' and k == 1 and {q}", n)
        rows += [dict(dataset="THINGS test (k = 1)", units=units, convention=r.convention, subject=r.subject, delta=r.delta) for r in b.itertuples()]
        c = read("step48/conventions.csv", f"kind == 'nsd_subject' and k == 1 and {q}", n)
        rows += [dict(dataset="NSD (k = 1)", units=units, convention=r.convention, subject=r.subject, delta=r.delta) for r in c.itertuples()]
    df = pd.DataFrame(rows)
    fig, axes = plt.subplots(1, 2, figsize=(TWO, 2.6), sharey=True)
    for ax, units, title in zip(axes, ("raw", "z"), ("Raw model units (paper cell)", "Standardised model units")):
        x = 0
        ticks, labels = [], []
        for ds, convs in CONVS.items():
            for cv in convs:
                v = df[(df.dataset == ds) & (df.units == units) & (df.convention == cv)].delta.to_numpy()
                col = CCOL[cv.split("-")[1]]
                jit = np.linspace(-0.12, 0.12, len(v))
                ax.scatter(x + jit, v, s=7, color=col, alpha=0.6, lw=0)
                ax.errorbar(x + 0.28, v.mean(), yerr=v.std(ddof=1), fmt="o", ms=4, color=col, capsize=2, lw=1)
                ticks.append(x)
                labels.append(cv)
                x += 1
            x += 0.6
        ax.axhline(0, color="k", lw=0.6)
        ax.set_xticks(ticks)
        ax.set_xticklabels(labels, rotation=60, ha="right")
        ax.set_title(title)
        for i, ds in enumerate(CONVS):
            ax.text(1 + i * 3.6, ax.get_ylim()[1] if False else 0.215, ds, ha="center", fontsize=7)
    axes[0].set_ylabel(r"$\Delta$ = untrained $-$ Backprop (V1)")
    axes[0].set_ylim(-0.06, 0.23)
    fig.tight_layout()
    save(fig, n, df)


def fig_nsd():
    n = "nsd"
    rows = []
    for roi in ("V1", "LO-obj"):
        for (u, d), lab in ((("raw", "correlation"), "raw, corr."), (("z", "correlation"), "z, corr."), (("raw", "euclidean"), "raw, Eucl.")):
            a = read("step48/conventions.csv", f"kind == 'nsd_subject' and convention == 'N-session' and k == 3 and roi == '{roi}' "
                     f"and units == '{u}' and distance == '{d}'", n)
            rows += [dict(roi=roi, cell=lab, subject=r.subject, delta=r.delta) for r in a.itertuples()]
        for comp in ("N", "A"):
            s = read("step42/subjects.csv", f"kind == 'rho' and roi == '{roi}' and k == 3 and model_units == 'center' and distance == '{comp}'", n)
            m = s.groupby(["subject", "condition"]).rho.mean().unstack()
            rand = [c for c in m.columns if c.lower().startswith("random")][0]
            bp = [c for c in m.columns if c.lower() in ("bp", "backprop")][0]
            rows += [dict(roi=roi, cell=comp, subject=sub, delta=float(m.loc[sub, rand] - m.loc[sub, bp])) for sub in m.index]
        r = read("step47/nsd_ridge.csv", f"kind == 'subject' and roi == '{roi}' and grid == 4", n)
        rows += [dict(roi=roi, cell="ridge g = 4", subject=x.subject, delta=x.delta) for x in r.itertuples()]
    df = pd.DataFrame(rows)
    cells = ["raw, corr.", "z, corr.", "raw, Eucl.", "N", "A", "ridge g = 4"]
    fig, axes = plt.subplots(1, 2, figsize=(TWO, 2.4), sharey=True)
    for ax, roi in zip(axes, ("V1", "LO-obj")):
        for i, c in enumerate(cells):
            q = df[(df.roi == roi) & (df.cell == c)]
            others = q[q.subject != "subj01"].delta.to_numpy()
            ax.scatter(i + np.linspace(-0.15, 0.15, len(others)), others, s=9, color=OI["grey"], lw=0)
            s1 = q[q.subject == "subj01"].delta
            ax.scatter([i], s1, s=22, marker="D", color=OI["vermillion"], lw=0, label="subj01" if i == 0 else None)
            ax.plot([i - 0.25, i + 0.25], [q.delta.mean()] * 2, color="k", lw=1.2)
        ax.axhline(0, color="k", lw=0.6)
        ax.set_xticks(range(len(cells)))
        ax.set_xticklabels(cells, rotation=40, ha="right")
        ax.set_title(roi)
    axes[0].set_ylabel(r"$\Delta$ = untrained $-$ Backprop")
    axes[0].legend(frameon=False, loc="lower left")
    fig.tight_layout()
    save(fig, n, df)


def fig_multi():
    n = "multi"
    mv = read("step43/multiverse_nsd.csv", "kind == 'cell' and roi == 'V1'", n)
    reps = mv.groupby("cls", sort=True).head(1)
    th = read("step7/multiverse.csv", "kind == 'cell' and roi == 'V1' and quantity == 'gap NATIVE 224: Random Weights - Backprop'", n)
    nr = read("step48/conventions.csv", "kind == 'nsd_multiverse_cell' and roi == 'V1'", n)
    rows = []
    for r in reps.itertuples():
        key = (r.F, r.D, r.B)
        t = th[(th.F == r.F) & (th.D == r.D) & (th.B == r.B)].iloc[0]
        x = nr[(nr.F == r.F) & (nr.D == r.D) & (nr.B == r.B)].iloc[0]
        rows += [dict(cls=int(r.cls), cell="/".join(key), data="THINGS-720", delta=t.value, lo=t.ci_lo, hi=t.ci_hi),
                 dict(cls=int(r.cls), cell="/".join(key), data="NSD, N-session", delta=r.mean_delta, lo=r.ci_lo, hi=r.ci_hi),
                 dict(cls=int(r.cls), cell="/".join(key), data="NSD, N-raw", delta=x.delta, lo=x.ci_lo, hi=x.ci_hi)]
    df = pd.DataFrame(rows)
    order = df[df.data == "THINGS-720"].sort_values("delta").cls.tolist()
    fig, ax = plt.subplots(figsize=(TWO, 2.7))
    for j, (dname, col) in enumerate((("THINGS-720", OI["orange"]), ("NSD, N-session", OI["blue"]), ("NSD, N-raw", OI["vermillion"]))):
        q = df[df.data == dname].set_index("cls").loc[order]
        xs = np.arange(len(order)) + (j - 1) * 0.25
        ax.errorbar(xs, q.delta, yerr=[q.delta - q.lo, q.hi - q.delta], fmt="o", ms=2.5, color=col, lw=0.7, capsize=0, label=dname)
    ax.axhline(0, color="k", lw=0.6)
    ax.set_xticks(range(len(order)))
    ax.set_xticklabels([df[(df.cls == c)].cell.iloc[0].replace("correlation", "corr").replace("euclidean", "eucl").replace("cosine", "cos")
                        .replace("center720", "c720").replace("paper", "own") for c in order], rotation=90, fontsize=5.5)
    ax.set_ylabel(r"$\Delta$ (V1)")
    ax.legend(frameon=False, ncol=3, loc="upper left")
    fig.tight_layout()
    save(fig, n, df)


def fig_amp():
    n = "amp"
    rows = []
    for ds, cv, lab in (("things720", "T-global", "THINGS-720, T-global"), ("things720", "T-raw", "THINGS-720, T-raw"),
                        ("nsd515", "N-raw", "NSD, N-raw"), ("nsd515", "N-session", "NSD, N-session")):
        k = 1
        b = read("step48/amplitude.csv", f"kind == 'brain_gain_stat' and dataset == '{ds}' and convention == '{cv}' and roi == 'V1' "
                 f"and k == {k} and stat in ('L', 'C', 'CE')", n)
        for st, g in b.groupby("stat"):
            rows.append(dict(panel="brain g", group=lab, stat=st, value=g.rho.mean()))
    for ds, lab in (("things720", "THINGS-720"), ("nsd515", "NSD")):
        m = read("step48/amplitude.csv", f"kind == 'model_gain_stat' and dataset == '{ds}' and layer == 'Conv1' and stat in ('L', 'C', 'CE')", n)
        for (c, st), g in m.groupby(["condition", "stat"]):
            rows.append(dict(panel="model gM", group=f"{lab}, {'untrained' if c == 'Random' else 'Backprop'}", stat=st, value=g.rho.mean()))
    d = read("step48b/dominance.csv", "kind == 'model_dominance' and form == 'sum' and layer == 'Conv1'", n)
    for r in d.itertuples():
        rows.append(dict(panel="dominance", group=r.dataset, stat=r.condition, value=r.rho, seed=r.seed))
    p = read("step48b/partial.csv", "kind == 'delta' and roi == 'V1' and form in ('none', 'sum') and "
             "((dataset == 'things720' and convention in ('T-raw', 'T-global')) or (dataset == 'things_test' and convention == 'T-raw' and k == 12) "
             "or (dataset == 'nsd515' and convention == 'N-raw' and k == 1))", n)
    for r in p.itertuples():
        rows.append(dict(panel="partial", group=f"{r.dataset} {r.convention} k={int(r.k)}", stat=r.form, value=r.delta))
    df = pd.DataFrame(rows)
    fig, axes = plt.subplots(1, 3, figsize=(TWO, 2.5), gridspec_kw={"width_ratios": [2.1, 0.9, 1.0]})
    ax = axes[0]
    groups = [g for g in df[df.panel == "brain g"].group.unique()] + [g for g in df[df.panel == "model gM"].group.unique()]
    stcol = {"L": OI["grey"], "C": OI["skyblue"], "CE": OI["green"]}
    for i, g in enumerate(groups):
        q = df[(df.group == g) & df.panel.isin(["brain g", "model gM"])].set_index("stat")
        for j, st in enumerate(("L", "C", "CE")):
            ax.bar(i + (j - 1) * 0.27, q.loc[st, "value"], width=0.26, color=stcol[st], label=st if i == 0 else None)
    ax.axhline(0, color="k", lw=0.6)
    ax.axvline(3.5, color="k", lw=0.4, ls=":")
    ax.set_xticks(range(len(groups)))
    short_g = {"THINGS-720, T-global": "720\nT-global", "THINGS-720, T-raw": "720\nT-raw", "NSD, N-raw": "NSD\nN-raw",
               "NSD, N-session": "NSD\nN-sess.", "THINGS-720, untrained": "720\nuntr.", "THINGS-720, Backprop": "720\nBP",
               "NSD, untrained": "NSD\nuntr.", "NSD, Backprop": "NSD\nBP"}
    ax.set_xticklabels([short_g.get(g, g) for g in groups], fontsize=6)
    ax.set_ylabel("Spearman with image statistic")
    ax.set_title(r"(a) brain $g$ (left), model $g^M$ (right)")
    ax.legend(frameon=False, fontsize=6)
    ax = axes[1]
    for i, ds in enumerate(("things720", "things_test", "nsd515")):
        for c, col, off in (("Random", OI["vermillion"], -0.15), ("BP", OI["blue"], 0.15)):
            v = df[(df.panel == "dominance") & (df.group == ds) & (df.stat == c)].value
            ax.scatter(np.full(len(v), i + off), v, s=9, color=col, lw=0, label=({"Random": "untrained", "BP": "Backprop"}[c] if i == 0 else None))
    ax.set_xticks(range(3))
    ax.set_xticklabels(["720", "test", "NSD"], fontsize=7)
    ax.set_ylabel(r"Spearman(model RDM, $A^M$)")
    ax.set_title("(b) model amplitude dominance")
    ax.legend(frameon=False, fontsize=6)
    ax = axes[2]
    pq = df[df.panel == "partial"]
    labs = list(dict.fromkeys(pq.group))
    for i, g in enumerate(labs):
        q = pq[pq.group == g].set_index("stat").value
        ax.plot([i, i], [q["none"], q["sum"]], color=OI["grey"], lw=0.8)
        ax.scatter([i], [q["none"]], color=OI["vermillion"], s=14, label="before" if i == 0 else None)
        ax.scatter([i], [q["sum"]], color=OI["black"], s=14, marker="x", label="after two-sided partial" if i == 0 else None)
    ax.axhline(0, color="k", lw=0.6)
    short = {"things720 T-raw k=1": "720\nT-raw", "things720 T-global k=1": "720\nT-global", "things_test T-raw k=12": "test\nT-raw",
             "nsd515 N-raw k=1": "NSD\nN-raw"}
    ax.set_xticks(range(len(labs)))
    ax.set_xticklabels([short.get(g, g) for g in labs], fontsize=6)
    ax.set_ylabel(r"$\Delta$ (V1)")
    ax.set_title("(c) partial on amplitude")
    ax.legend(frameon=False, fontsize=6)
    fig.tight_layout()
    save(fig, n, df)


if __name__ == "__main__":
    fig_conv()
    fig_nsd()
    fig_multi()
    fig_amp()
    print("wrote conv, nsd, multi, amp")
