"""
config_hash.py
==============
One definition of the config hash, shared by every script that writes a CSV.

The hash covers the SEMANTIC content of config.yaml, not its bytes: the YAML is
parsed and re-serialised as canonical JSON with sorted keys before hashing. So
reformatting a comment or reordering a block does not change the hash, while
changing any value does.

Usage:
    from config_hash import load_config, config_hash
    cfg = load_config()
    h = config_hash()            # 12-char short hash, goes in every CSV
    df["config_hash"] = h

CLI:
    python code/ridge/config_hash.py            # print the hash
    python code/ridge/config_hash.py --lock     # write config.lock
    python code/ridge/config_hash.py --check    # verify config.lock still matches
"""

import hashlib
import json
import sys
from pathlib import Path

import yaml

__all__ = ["REPO_ROOT", "CONFIG_PATH", "LOCK_PATH",
           "load_config", "config_hash", "config_hash_full", "check_lock"]

REPO_ROOT = Path(__file__).resolve().parents[2]
CONFIG_PATH = REPO_ROOT / "config.yaml"
LOCK_PATH = REPO_ROOT / "config.lock"

SHORT_LEN = 12


def load_config(path: Path = None) -> dict:
    """Parse config.yaml. Raises if it is missing — never returns a default.

    A silently defaulted config is the same class of failure as a silently
    random-initialised model: the run looks correct and is not.
    """
    path = Path(path) if path is not None else CONFIG_PATH
    if not path.exists():
        raise FileNotFoundError(
            f"config.yaml not found at {path}. Every output CSV must carry a "
            "config hash, so there is no default and no fallback."
        )
    with open(path, "r", encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    if not isinstance(cfg, dict) or "schema_version" not in cfg:
        raise ValueError(
            f"{path} did not parse to a mapping with a schema_version key; "
            "refusing to hash a config we cannot interpret."
        )
    return cfg


def _canonical(cfg: dict) -> str:
    """Canonical JSON: sorted keys, no incidental whitespace.

    sort_keys makes the hash independent of YAML block order. default=str keeps
    it total over the scalar types PyYAML can emit (dates, for instance) rather
    than raising on one and silently succeeding on the rest.
    """
    return json.dumps(cfg, sort_keys=True, separators=(",", ":"), default=str)


def config_hash_full(cfg: dict = None) -> str:
    """Full sha256 hex digest of the canonical config."""
    cfg = load_config() if cfg is None else cfg
    return hashlib.sha256(_canonical(cfg).encode("utf-8")).hexdigest()


def config_hash(cfg: dict = None) -> str:
    """Short hash for the `config_hash` CSV column."""
    return config_hash_full(cfg)[:SHORT_LEN]


def check_lock() -> bool:
    """True if config.lock matches the current config.yaml.

    Returns False rather than raising so callers can choose; the CLI --check
    exits non-zero.
    """
    if not LOCK_PATH.exists():
        return False
    recorded = None
    for line in LOCK_PATH.read_text(encoding="utf-8").splitlines():
        if line.startswith("sha256:"):
            recorded = line.split(":", 1)[1].strip()
    return recorded == config_hash_full()


def _write_lock() -> str:
    cfg = load_config()
    full = config_hash_full(cfg)
    LOCK_PATH.write_text(
        "# config.lock — generated by code/ridge/config_hash.py\n"
        "# Semantic hash of config.yaml (canonical JSON, sorted keys).\n"
        "# Regenerate deliberately, never to make a check pass.\n"
        f"schema_version: {cfg['schema_version']}\n"
        f"short: {full[:SHORT_LEN]}\n"
        f"sha256: {full}\n",
        encoding="utf-8",
    )
    return full


if __name__ == "__main__":
    if "--lock" in sys.argv:
        full = _write_lock()
        print(f"wrote {LOCK_PATH.name}: {full[:SHORT_LEN]}  ({full})")
    elif "--check" in sys.argv:
        if check_lock():
            print(f"config.lock matches: {config_hash()}")
        else:
            print(f"MISMATCH: config.yaml hashes to {config_hash()}, "
                  f"config.lock says otherwise (or is absent)")
            sys.exit(1)
    else:
        cfg = load_config()
        print(f"schema_version {cfg['schema_version']}  hash {config_hash(cfg)}")
        print(f"sha256 {config_hash_full(cfg)}")
